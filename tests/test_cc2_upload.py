async def test_the_lock_is_held_across_the_whole_operation_and_released_after(tmp_path, store):
    src = write_gcode(tmp_path)
    inside_lock = []
    lockfile = store.locks_dir / (hashlib.sha256(SN.encode()).hexdigest()[:32] + ".lock")

    def peek_inside(n, headers, body):
        # mid-transfer, a second caller opening THIS printer's lock file must not get it
        import fcntl
        probe = os.open(lockfile, os.O_CREAT | os.O_RDWR, 0o600)
        try:
            fcntl.flock(probe, fcntl.LOCK_EX | fcntl.LOCK_NB)
            inside_lock.append("stolen")  # pragma: no cover — must never happen
        except OSError:
            inside_lock.append("held")
        finally:
            os.close(probe)

    tr = FakeTransport([("other.gcode", 1)], [("other.gcode", 1), (DEST, src.stat().st_size)])
    await run(tr, src, store=store, http=FakeHttp(hook=peek_inside))
    assert set(inside_lock) == {"held"}
    held = store.lock(SN)  # and when the upload is done, the lock is genuinely released
    held.__enter__()
    held.__exit__(None, None, None)
    lockfiles = list(store.locks_dir.iterdir())
    assert lockfiles and all(stat.S_IMODE(p.stat().st_mode) == 0o600 for p in lockfiles)


