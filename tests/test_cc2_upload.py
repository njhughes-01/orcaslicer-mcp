def test_a_receipt_file_filed_under_the_wrong_identity_is_refused(tmp_path):
    store = Cc2ReceiptStore(tmp_path / "s")
    r = _sample_receipt()
    store.save(r)
    alien_path = store.path_for("OTHERSN00001", DEST)
    alien_path.parent.mkdir(parents=True, exist_ok=True)
    alien_path.write_bytes(store.path_for(SN, DEST).read_bytes())  # right bytes, wrong drawer
    with pytest.raises(PrinterError):
        store.load("OTHERSN00001", DEST)  # the receipt names CC2TESTSN0001, not this caller
    with open(alien_path, "w") as f:
        f.write("this is not a receipt")
    fresh = Cc2ReceiptStore(tmp_path / "s2")
    fresh.save(r)
    corrupt = fresh.path_for(SN, DEST)
    corrupt.write_text("{ not json", encoding="utf-8")
    with pytest.raises(PrinterError):
        fresh.load(SN, DEST)  # corrupt is a trust failure, never a quiet None


