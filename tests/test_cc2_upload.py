def _heat_frame(*lines, material="PLA", plate="High Temp Plate", nozzle=240.0, bed=60.0):
    """A minimal single-tool file with these command lines and this config block, the commands
    kept verbatim and in the order given — so an order test tests exactly its own order."""
    cfg = ("; printer_model = Elegoo Centauri Carbon 2\n"
           f"; curr_bed_type = {plate}\n; filament_type = {material}\n"
           f"; nozzle_temperature = {nozzle:g}\n"
           f"; nozzle_temperature_initial_layer = {nozzle:g}\n"
           f"; hot_plate_temp = {bed:g}\n; hot_plate_temp_initial_layer = {bed:g}\n")
    return "\n".join(lines) + "\n" + cfg


def test_preheat_then_wait_then_purge_is_the_working_mount_frame_and_is_accepted():
    # the actual mount file's shape: a 140 °C non-extruding preheat, one wait up to the print
    # temperature, then the purge and its E moves — accepted, recording only the waited-for
    # temperature, because no range is hardcoded and no number here is special
    s = up.parse_gcode_text(_heat_frame(
        "M104 S140", "M140 S60", "M190 S60 A", "M109 S240",
        "M6211 A1 L200 T0 Q240 R240 S240", "T0",
        "G1 X127 Y-1.2 F20000", "G1 E6 F131.773", "M104 S0", "M140 S0"))
    assert s.nozzle_setpoints == (140.0, 240.0)  # preheat stays visible evidence
    assert s.extrusion_nozzle_temps == (240.0,)  # extrusion ran only where a wait proved it
    assert s.bed_setpoints == (60.0,)


