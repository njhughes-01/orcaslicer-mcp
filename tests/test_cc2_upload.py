class FakeHttp:
    """One chunk-sending session, answering from a per-call script of Cc2ChunkResponse objects
    or exceptions (default: the observed success frame). Records every PUT's headers and body in
    the order asked, runs an optional hook after recording (the mid-upload mutation tests), and
    counts aclose() calls so cleanup can be proven on every path."""

    def __init__(self, script=(), hook=None):
        self.puts: list[dict] = []
        self.closes = 0
        self.base_urls: list[str] = []
        self.script = list(script)
        self.hook = hook

    def factory(self):
        def make(base_url: str) -> FakeHttp:
            self.base_urls.append(base_url)
            return self
        return make

    async def put_chunk(self, *, body: bytes, headers: dict[str, str]):
        self.puts.append({"body": body, "headers": dict(headers)})
        if self.hook is not None:
            self.hook(len(self.puts), dict(headers), body)
        item = self.script[len(self.puts) - 1] if len(self.puts) <= len(self.script) \
            else OK_CHUNK
        if isinstance(item, BaseException):
            raise item
        return item

    async def aclose(self) -> None:
        self.closes += 1

    # conveniences for assertions -----------------------------------------------------------
    @property
    def ranges(self) -> list[str]:
        return [p["headers"]["Content-Range"] for p in self.puts]

    @property
    def names(self) -> list[str]:
        return [p["headers"]["X-File-Name"] for p in self.puts]

    @property
    def tokens(self) -> list[str]:
        return [p["headers"]["X-Token"] for p in self.puts]

    @property
    def md5s(self) -> list[str]:
        return [p["headers"]["X-File-MD5"] for p in self.puts]

    @property
    def bodies(self) -> list[bytes]:
        return [p["body"] for p in self.puts]


def resp(status: int = 200, body: bytes = b'{"error_code": 0}'):
    return up.Cc2ChunkResponse(status_code=status, body=body)


OK_CHUNK = resp()


@pytest.fixture
def store(tmp_path) -> Cc2ReceiptStore:
    return Cc2ReceiptStore(tmp_path / "receipts")


async def run(transport, src, *, destination=DEST, token=TOKEN, store=None, http=None,
              chunk_size=CHUNK):
    http = http if http is not None else FakeHttp()
    receipt = await up.upload_gcode(transport, src, destination, token=token, store=store,
                                    http_factory=http.factory(), chunk_size=chunk_size)
    return receipt, http


