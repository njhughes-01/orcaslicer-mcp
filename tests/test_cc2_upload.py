def gcode_text(*, material="PETG", plate="High Temp Plate",
               nozzle_first=260.0, nozzle=260.0, bed_first=70.0, bed=70.0, flush=140.0,
               tools=("T0",), mid_bed=70.0, tail_cool=True, temp_trail=False, mid_s0=False,
               omit=(), omit_nozzle_cmds=False, omit_bed_cmds=False, config_extra=()):
    """The uploaded reference slice, trimmed to the lines that matter and shaped field-for-field
    like it: start block, a first-layer set, the tool select inside the M6211 flush line as well
    as on its own, a repeat ``M109`` before the purge move, one mid-print ``M140`` carrying the
    layer-apply temperature, the end block's S0 cooldowns, then the tail config block. The traps
    are load-bearing: ``M6211`` carries a T parameter, and the template config lines quote whole
    start-G-code programs — a parser that reads comments or substrings as commands fails here.
    Every frame it writes declares the CC2 printer model (design 1's gate): omit it with
    ``omit=("model",)``."""
    o = set(omit)

    def cmd(line, key):
        return "" if key in o else line + "\n"

    text = "; generated by OrcaSlicer (Elegoo C2 profile) — trimmed reference frame\n"
    text += "G90\n"
    text += cmd(f"M104 S{flush:g}", "flush") if flush is not None else ""
    if "bed_cmds" not in o and not omit_bed_cmds:
        text += f"M140 S{bed_first:g}\nM190 S{bed_first:g} A\n"
    text += "M106 S0\n"
    if not omit_nozzle_cmds:
        text += f"M109 S{nozzle_first:g}\n"
    m6211 = f"M6211 A1 L200 {tools[0]} Q{nozzle_first:g} R{nozzle_first:g} S{nozzle_first:g}\n"
    text += "" if "m6211" in o else m6211
    for t in () if "tools" in o else tools:
        text += f"{t}\n"
    if not omit_nozzle_cmds:  # the reference file repeats the M109 around the purge move
        text += f"M109 S{nozzle:g}\n"
    text += "G1 X127 Y-1.2 F20000\nG1 E6 F131.773\n"
    if mid_bed is not None and not omit_bed_cmds:
        text += f"M140 S{mid_bed:g} ; set bed temperature\n"
    if temp_trail:  # a second extruding pass; with mid_s0 the nozzle is switched off between
        if mid_s0:  # the passes — a cooldown before extrusions still to come, which no honest
            text += "M104 S0 ; nozzle off mid-file\n"  # file does and this parser must refuse
        if flush is not None:
            text += f"M104 S{flush:g}\n"
        text += f"M109 S{nozzle:g}\nG1 X120 Y-1.2 F20000\nG1 E3 F131.773\n"
    if tail_cool:
        text += "M104 S0\nM140 S0 ;Turn-off bed\n"
    text += "; CONFIG_BLOCK_START\n"
    if "model" not in o:
        text += "; printer_model = Elegoo Centauri Carbon 2\n"
    if plate is not None and "plate" not in o:
        text += f"; curr_bed_type = {plate}\n"
    if material is not None and "material" not in o:
        text += f"; filament_type = {material}\n"
    if nozzle is not None and "nozzle" not in o:
        text += f"; nozzle_temperature = {nozzle:g}\n"
    if nozzle_first is not None and "nozzle_first" not in o:
        text += f"; nozzle_temperature_initial_layer = {nozzle_first:g}\n"
    if bed is not None and "bed" not in o:
        text += f"; hot_plate_temp = {bed:g}\n"
    if bed_first is not None and "bed_first" not in o:
        text += f"; hot_plate_temp_initial_layer = {bed_first:g}\n"
    text += "; nozzle_temperature_range_low = 190\n; nozzle_temperature_range_high = 240\n"
    if "template_traps" not in o:  # templates quote commands and selects as inert text
        text += ("; machine_start_gcode = ;===== C2_START_GCODE ================\\nM104 S140\\n"
                 "M109 S[nozzle_temperature_initial_layer]\\nT[initial_no_support_extruder]\\n\n")
        text += ("; change_filament_gcode = \\nM6211 T[next_extruder] L[flush_length]\\n"
                 "T[next_extruder]\\n\n")
    text += "\n".join(config_extra) + "\n" if config_extra else ""
    text += "; CONFIG_BLOCK_END\n"
    return text


def write_gcode(dirpath: Path, name: str = "part.gcode", *, newline="\n", pad_to: int = 0,
                **kw) -> Path:
    text = gcode_text(**kw)
    body = text.replace("\n", newline)
    if pad_to:
        assert pad_to > len(body.encode()), "pad_to must exceed the content length"
        body += "\n" * (pad_to - len(body.encode()))  # blank lines: valid G-code, parse-irrelevant
    path = dirpath / name
    path.write_bytes(body.encode())
    return path


