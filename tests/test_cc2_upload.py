class FakeTransport:
    """Stands in for the registered session the way cc2_state's Scripted did, narrowed to the
    one method an upload asks: 1044. Each list_files() pass consumes the next listing snapshot
    (the last repeats forever); a snapshot is a list of (name, size) plus optional 'total' —
    short of total with paging ignored is a simulated capped-100 shape, which cc2_state must
    refuse. Anything else on the wire is unknown, and unknown raises here exactly as it does
    live."""

    def __init__(self, *snapshots, host=HOST, sn=SN, display="CC2-test"):
        self.host, self.sn, self.display = host, sn, display
        self.snapshots = list(snapshots) or [[("other-calibration-mark.gcode", 123)]]
        self.calls = 0
        self.requests: list[tuple[int, dict]] = []

    def _snapshot(self):
        snap = self.snapshots[min(self.calls, len(self.snapshots) - 1)]
        self.calls += 1
        if isinstance(snap, dict):  # {"files": [...], "total": n} — a total that outstrips the page
            return snap["files"], snap.get("total", len(snap["files"]))
        return list(snap), len(snap)

    async def request(self, method: int, params: dict | None = None, *, timeout_s=None) -> dict:
        assert method == st.METHOD_FILES, f"the upload asks only 1044, not {method}"
        params = params or {}
        assert params.get("storage_media") == "local"
        self.requests.append((method, dict(params)))
        files, total = self._snapshot()
        return {"error_code": 0, "total": total,
                "file_list": [{"filename": n, "size": s, "type": "file"} for n, s in files]}



def short_listing(files):  # a simulated capped reply: fewer files than the reported total
    return {"files": files, "total": len(files) + 1}


