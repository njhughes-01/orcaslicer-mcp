"""CC2 direct upload and its private receipt, against a scripted 1044 listing and a fake chunk
sender: nothing here opens a socket, and every wire fact is the observed one. The chunk frame is
the one the working direct upload sent and the Elegoo SDK documents: PUT to port 80 of the pinned
private address, 1 MiB raw chunks, ``Content-Range: bytes <start>-<end>/<total>`` inclusive,
``X-File-Name``, whole-file ``X-File-MD5`` on every chunk, ``X-Token``, success answered as HTTP
200 + JSON ``error_code`` 0. The offset-like reply fields were never observed to mean anything
and carry no documented required acknowledgment, so no test requires or reads one. The G-code
fixture is a trim of the reference slice actually uploaded to this printer on 2026-11-04 — the
140 °C flush hold before ``M109 S260``, the ``M6211 ... T0 ...`` flush command whose T parameter
is a real filament select (the firmware runs ``CANVAS_SWITCH_FILAMENT T=<n>`` inside the purge), the
trailing cooldown S0s, and the tail config block whose four setpoints must appear among the
commands. Those heater commands are additionally read in order: the 140 °C flush hold is legal
because it never extrudes, the purge and every E move may only run behind an M109 that waited at
exactly the target in force, a target changed after a wait needs another matching wait, and the
current cooldown S0s are legal because nothing extrudes after them — so the receipt's extrusion
temperatures record what extrusion provably ran at, never a preheat the working mount file also
commands. Failures are proven once-each: no chunk is ever resent, no overwrite is ever attempted,
an incomplete listing is never a green light, a source that moves mid-upload stops everything
before the receipt, and the receipt — mode 600 under a 700 store — binds serial, name, size,
SHA-256 and the parsed settings with no token, no G-code text and no raw reply in it."""
