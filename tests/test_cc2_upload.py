async def test_offset_like_reply_fields_never_decide_anything(tmp_path, store):
    # the SDK documents success as the HTTP status plus error_code alone; this printer's own
    # offset-flavoured fields were never observed to mean anything, so this adapter neither
    # requires one nor lets one overrule an error_code — invented ack semantics are absent here
    src = write_gcode(tmp_path)
    size = src.stat().st_size
    yes = resp(200, b'{"error_code": 0, "offset": 123456}')
    weird = resp(200, b'{"error_code": 0, "offset": -999, "size": "nonsense"}')
    tr = FakeTransport([("other.gcode", 1)], [("other.gcode", 1), (DEST, size)])
    receipt, http = await run(tr, src, store=store, http=FakeHttp(script=[yes, weird]))
    assert receipt is not None and len(http.puts) == -(-size // CHUNK)
    lie = resp(200, b'{"error_code": 5, "offset": 64}')  # the offset promises; the code declines
    tr = FakeTransport([("other.gcode", 1)], [(DEST, size)])
    with pytest.raises(PrinterError) as bad:
        await run(tr, src, store=store, http=FakeHttp(script=[yes, lie]))
    assert "error_code 5" in bad.value.message and bad.value.details["reason"] == \
        "upload_chunk_failed"
